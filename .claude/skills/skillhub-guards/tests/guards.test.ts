import type { On } from 'claude-code'
import { expect, test } from 'claude-code/testing'
import {
  attributedToCommand, isAgentCache, isGeneratedHeader, needsSignature, spawnProblem, subagentCommandProblem,
} from '../hooks/register'

const PARENT = 'claude-opus-5-5'

test('a subagent with no model and no role is refused', () => {
  expect(spawnProblem(undefined, 'general-purpose', PARENT, false)).toMatch(/name a model/)
})

test('a repository role without a model is allowed, its frontmatter pins one', () => {
  expect(spawnProblem(undefined, 'skillhub-writer', PARENT, false)).toBeUndefined()
})

test('a subagent on the dispatcher\'s own family is refused', () => {
  expect(spawnProblem('opus', 'general-purpose', PARENT, false)).toMatch(/dispatcher's own tier/)
})

test('a subagent one tier below the dispatcher is allowed', () => {
  expect(spawnProblem('sonnet', 'general-purpose', PARENT, false)).toBeUndefined()
})

test('fable is refused even under a fable-less dispatcher', () => {
  expect(spawnProblem('fable', 'general-purpose', 'claude-sonnet-5-5', false)).toMatch(/dispatcher's own tier/)
})

test('opus is allowed when the dispatcher is fable', () => {
  expect(spawnProblem('opus', 'Explore', 'claude-fable-5-1', false)).toBeUndefined()
})

test('a fork is refused whatever model it names, it always runs on the dispatcher\'s', () => {
  expect(spawnProblem('haiku', 'fork', PARENT, true)).toMatch(/fork/)
})

