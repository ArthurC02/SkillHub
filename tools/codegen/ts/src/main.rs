use serde_json::{Map, Value};
use std::collections::BTreeMap;
use std::fs;
use std::path::Path;
use std::process::ExitCode;

type Object = Map<String, Value>;

const NULL_TYPE: &str = "null";
const SCHEMA_REF_PREFIX: &str = "#/components/schemas/";
const LINT_DISABLE: &str = "/* tslint:disable */\n/* eslint-disable */\n";

fn main() -> ExitCode {
    let args: Vec<String> = std::env::args().collect();
    if args.len() != 3 {
        eprintln!("usage: openapi-ts <openapi.yaml> <out-dir>");
        return ExitCode::from(2);
    }
    match run(Path::new(&args[1]), Path::new(&args[2])) {
        Ok(count) => {
            println!("openapi-ts: wrote {count} models");
            ExitCode::SUCCESS
        }
        Err(message) => {
            eprintln!("openapi-ts: {message}");
            ExitCode::FAILURE
        }
    }
}

fn run(spec: &Path, out: &Path) -> Result<usize, String> {
    let text = fs::read_to_string(spec).map_err(|e| format!("{}: {e}", spec.display()))?;
    let doc: Value =
        serde_saphyr::from_str(&text).map_err(|e| format!("{}: {e}", spec.display()))?;
    let mut generator = Generator::new(&doc)?;
    generator.collect();
    let models = out.join("models");
    fs::create_dir_all(&models).map_err(|e| format!("{}: {e}", models.display()))?;
    let header = generator.header();
    for (name, model) in &generator.models {
        let path = models.join(format!("{name}.ts"));
        fs::write(&path, format!("{header}{}", model.render(name)))
            .map_err(|e| format!("{}: {e}", path.display()))?;
    }
    let barrel: String = generator
        .models
        .keys()
        .map(|name| format!("export * from './{name}';\n"))
        .collect();
    fs::write(models.join("index.ts"), format!("{header}{barrel}"))
        .map_err(|e| format!("models/index.ts: {e}"))?;
    fs::write(
        out.join("index.ts"),
        format!("{header}export * from './models/index';\n"),
    )
    .map_err(|e| format!("index.ts: {e}"))?;
    Ok(generator.models.len())
}

struct Generator<'a> {
    schemas: &'a Object,
    paths: &'a Object,
    info: &'a Object,
    models: BTreeMap<String, Model>,
    inline_shapes: Vec<(Value, String)>,
}

enum Model {
    Interface {
        description: String,
        properties: Vec<Property>,
        enums: Vec<EnumDef>,
        imports: Vec<String>,
        has_enums: bool,
    },
    Alias {
        description: String,
        ts_type: String,
        imports: Vec<String>,
    },
    Enum {
        description: String,
        values: Vec<Value>,
    },
}

struct Property {
    name: String,
    optional: bool,
    ts_type: String,
    description: String,
}

struct EnumDef {
    name: String,
    values: Vec<Value>,
}

struct Field {
    name: String,
    schema: Object,
    origin: String,
}

struct Context<'m> {
    model: String,
    origin: String,
    enums: &'m mut Vec<EnumDef>,
    imports: &'m mut Vec<String>,
    is_enum: bool,
    moves_description: bool,
    alias_description: Option<String>,
}

impl<'a> Generator<'a> {
    fn new(doc: &'a Value) -> Result<Self, String> {
        let object = |path: &[&str]| -> Result<&'a Object, String> {
            let mut node = doc;
            for key in path {
                node = node
                    .get(key)
                    .ok_or_else(|| format!("missing {}", path.join(".")))?;
            }
            node.as_object()
                .ok_or_else(|| format!("{} is not a mapping", path.join(".")))
        };
        Ok(Self {
            schemas: object(&["components", "schemas"])?,
            paths: object(&["paths"])?,
            info: object(&["info"])?,
            models: BTreeMap::new(),
            inline_shapes: Vec::new(),
        })
    }

    fn header(&self) -> String {
        let title = text(self.info, "title");
        let description = text(self.info, "description").replace('\n', " ");
        let version = text(self.info, "version");
        format!(
            "{LINT_DISABLE}/**\n * {title}\n * {description}\n *\n * The version of the OpenAPI document: {version}\n * \n *\n * NOTE: This file is generated by tools/codegen/ts from the OpenAPI contract.\n * Do not edit it manually.\n */\n\n"
        )
    }

    fn collect(&mut self) {
        for (name, schema) in self.schemas {
            if let Some(schema) = schema.as_object().filter(|s| !is_type_alias(s)) {
                self.define(&model_name(name), schema);
            }
        }
        for (_, operations) in self.paths {
            let Some(operations) = operations.as_object() else {
                continue;
            };
            for (_, operation) in operations {
                let Some(operation) = operation.as_object() else {
                    continue;
                };
                let Some(id) = operation.get("operationId").and_then(Value::as_str) else {
                    continue;
                };
                let id = pascal(id);
                if let Some(schema) = inline_body_schema(operation.get("requestBody")) {
                    self.define_inline(&format!("{id}Request"), schema);
                }
                let Some(responses) = operation.get("responses").and_then(Value::as_object) else {
                    continue;
                };
                for (status, response) in responses {
                    if let Some(schema) = inline_body_schema(Some(response)) {
                        self.define_inline(&format!("{id}{status}Response"), schema);
                    }
                }
            }
        }
    }

    fn define_inline(&mut self, name: &str, schema: &Object) -> String {
        let shape = Value::Object(schema.clone());
        if let Some(existing) = self.inline_shapes.iter().find(|(seen, _)| *seen == shape) {
            return existing.1.clone();
        }
        self.inline_shapes.push((shape, name.to_string()));
        self.define(name, schema);
        name.to_string()
    }

    fn define(&mut self, name: &str, schema: &Object) {
        if self.models.contains_key(name) {
            return;
        }
        let description = text(schema, "description");
        let model = if let Some(variants) = schema.get("oneOf").and_then(Value::as_array) {
            let mut imports = Vec::new();
            let ts_type = self.one_of(name, variants, schema.get("discriminator"), &mut imports);
            imports.sort();
            Model::Alias {
                description,
                ts_type,
                imports,
            }
        } else if let Some(values) = schema.get("enum").and_then(Value::as_array) {
            Model::Enum {
                description,
                values: values.clone(),
            }
        } else {
            let mut enums = Vec::new();
            let mut imports = Vec::new();
            let mut properties = Vec::new();
            let mut required = Vec::new();
            let mut fields = Vec::new();
            let mut has_enums = false;
            self.flatten(schema, name, &mut fields, &mut required);
            for field in fields {
                let mut context = Context {
                    model: name.to_string(),
                    origin: field.origin.clone(),
                    enums: &mut enums,
                    imports: &mut imports,
                    is_enum: false,
                    moves_description: false,
                    alias_description: None,
                };
                let ts_type = self.ts_type(&field.schema, &field.name, false, &mut context);
                has_enums |= context.is_enum;
                let description =
                    match (context.moves_description, context.alias_description.take()) {
                        (true, _) => String::new(),
                        (false, Some(alias)) => alias,
                        (false, None) => text(&field.schema, "description"),
                    };
                properties.push(Property {
                    name: camel(&field.name),
                    optional: !required.contains(&field.name),
                    ts_type,
                    description,
                });
            }
            imports.sort();
            Model::Interface {
                description,
                properties,
                enums,
                imports,
                has_enums,
            }
        };
        self.models.insert(name.to_string(), model);
    }

    fn flatten(
        &self,
        schema: &Object,
        origin: &str,
        fields: &mut Vec<Field>,
        required: &mut Vec<String>,
    ) {
        if let Some(reference) = schema.get("$ref").and_then(Value::as_str) {
            if let Some((name, target)) = self.resolve(reference) {
                self.flatten(target, &name, fields, required);
            }
            return;
        }
        if let Some(members) = schema.get("allOf").and_then(Value::as_array) {
            let members: Vec<&Object> = members.iter().filter_map(Value::as_object).collect();
            for member in members.iter().filter(|m| m.contains_key("$ref")) {
                self.flatten(member, origin, fields, required);
            }
            for member in members.iter().filter(|m| !m.contains_key("$ref")) {
                self.flatten(member, &format!("{origin}AllOf"), fields, required);
            }
        }
        if let Some(properties) = schema.get("properties").and_then(Value::as_object) {
            for (name, field_schema) in properties {
                let field_schema = field_schema.as_object().cloned().unwrap_or_default();
                match fields.iter_mut().find(|existing| existing.name == *name) {
                    Some(slot) => {
                        slot.schema = field_schema;
                        slot.origin = origin.to_string();
                    }
                    None => fields.push(Field {
                        name: name.clone(),
                        schema: field_schema,
                        origin: origin.to_string(),
                    }),
                }
            }
        }
        if let Some(names) = schema.get("required").and_then(Value::as_array) {
            for name in names.iter().filter_map(Value::as_str) {
                if !required.iter().any(|r| r == name) {
                    required.push(name.to_string());
                }
            }
        }
    }

    fn resolve(&self, reference: &str) -> Option<(String, &'a Object)> {
        let key = reference.strip_prefix(SCHEMA_REF_PREFIX)?;
        Some((model_name(key), self.schemas.get(key)?.as_object()?))
    }

    fn one_of(
        &mut self,
        name: &str,
        variants: &[Value],
        discriminator: Option<&Value>,
        imports: &mut Vec<String>,
    ) -> String {
        let mut arms: Vec<String> = Vec::new();
        for (index, variant) in variants.iter().filter_map(Value::as_object).enumerate() {
            let arm = if let Some(reference) = variant.get("$ref").and_then(Value::as_str) {
                ref_name(reference)
            } else {
                let title = text(variant, "title");
                let arm = if title.is_empty() {
                    format!("{name}OneOf{index}")
                } else {
                    title
                };
                self.define(&arm, variant);
                arm
            };
            imports.push(arm.clone());
            arms.push(arm);
        }
        if let Some(discriminator) = discriminator.and_then(Value::as_object) {
            let property = text(discriminator, "propertyName");
            if let Some(mapping) = discriminator.get("mapping").and_then(Value::as_object) {
                let mut tagged: Vec<(String, String)> = mapping
                    .iter()
                    .map(|(value, target)| (value.clone(), ref_name(target.as_str().unwrap_or(""))))
                    .collect();
                tagged.sort();
                return tagged
                    .iter()
                    .map(|(value, arm)| format!("{{ {property}: '{value}' }} & {arm}"))
                    .collect::<Vec<_>>()
                    .join(" | ");
            }
        }
        arms.sort();
        arms.join(" | ")
    }

    fn ts_type(
        &mut self,
        schema: &Object,
        field: &str,
        in_array: bool,
        context: &mut Context,
    ) -> String {
        if let Some(reference) = schema.get("$ref").and_then(Value::as_str) {
            let name = ref_name(reference);
            if let Some((_, target)) = self.resolve(reference) {
                if is_type_alias(target) {
                    context.alias_description = Some(text(target, "description"));
                    return self.ts_type(target, field, in_array, context);
                }
                context.is_enum |= target.contains_key("enum");
            }
            self.import(&name, context);
            return name;
        }
        if let Some(wrapped) = single_ref_wrapper(schema) {
            return self.ts_type(wrapped, field, in_array, context);
        }
        let (kind, nullable) = type_of(schema);
        let suffix = if nullable { " | null" } else { "" };
        if let Some(values) = schema.get("enum").and_then(Value::as_array) {
            let values = values.iter().filter(|v| !v.is_null()).cloned().collect();
            return format!("{}{suffix}", self.inline_enum(field, values, context));
        }
        if let Some(value) = schema.get("const") {
            return format!(
                "{}{suffix}",
                self.inline_enum(field, vec![value.clone()], context)
            );
        }
        if let Some(variants) = schema.get("oneOf").and_then(Value::as_array) {
            let (non_null, has_null) = without_null(variants);
            if let [only] = non_null.as_slice() {
                let inner = self.ts_type(only, field, in_array, context);
                return if has_null {
                    format!("{inner} | null")
                } else {
                    inner
                };
            }
            return format!(
                "{}{suffix}",
                self.inline_model(schema, field, in_array, context)
            );
        }
        if schema.contains_key("allOf") {
            return format!(
                "{}{suffix}",
                self.inline_model(schema, field, in_array, context)
            );
        }
        let base = match kind.as_str() {
            "array" => {
                let items = schema
                    .get("items")
                    .and_then(Value::as_object)
                    .cloned()
                    .unwrap_or_default();
                let inner = self.ts_type(&items, field, true, context);
                let container = if schema
                    .get("uniqueItems")
                    .and_then(Value::as_bool)
                    .unwrap_or(false)
                {
                    "Set"
                } else {
                    "Array"
                };
                format!("{container}<{inner}>")
            }
            "object" => {
                if schema.contains_key("properties") {
                    self.inline_model(schema, field, in_array, context)
                } else {
                    match schema.get("additionalProperties") {
                        Some(Value::Object(values)) => format!(
                            "{{ [key: string]: {}; }}",
                            self.ts_type(values, field, in_array, context)
                        ),
                        Some(Value::Bool(true)) => "{ [key: string]: any; }".to_string(),
                        _ => "object".to_string(),
                    }
                }
            }
            "string" => match text(schema, "format").as_str() {
                "date" | "date-time" => "Date",
                "binary" => "Blob",
                _ => "string",
            }
            .to_string(),
            "integer" | "number" => "number".to_string(),
            "boolean" => "boolean".to_string(),
            "" if schema.is_empty() => return "any | null".to_string(),
            _ => "any".to_string(),
        };
        format!("{base}{suffix}")
    }

    fn inline_enum(&mut self, field: &str, values: Vec<Value>, context: &mut Context) -> String {
        let name = format!("{}{}Enum", context.model, pascal(field));
        context.enums.push(EnumDef {
            name: name.clone(),
            values,
        });
        context.is_enum = true;
        name
    }

    fn inline_model(
        &mut self,
        schema: &Object,
        field: &str,
        in_array: bool,
        context: &mut Context,
    ) -> String {
        let suffix = if in_array { "Inner" } else { "" };
        let name = self.define_inline(
            &format!("{}{}{suffix}", context.origin, pascal(field)),
            schema,
        );
        self.import(&name, context);
        context.moves_description |= !in_array;
        name
    }

    fn import(&self, name: &str, context: &mut Context) {
        if name != context.model && !context.imports.iter().any(|existing| existing == name) {
            context.imports.push(name.to_string());
        }
    }
}

fn is_type_alias(schema: &Object) -> bool {
    let (kind, _) = type_of(schema);
    kind == "array" || (!kind.is_empty() && kind != "object" && !schema.contains_key("enum"))
}

fn inline_body_schema(holder: Option<&Value>) -> Option<&Object> {
    let content = holder?.as_object()?.get("content")?.as_object()?;
    let schema = content
        .get("application/json")?
        .as_object()?
        .get("schema")?
        .as_object()?;
    if schema.contains_key("$ref") {
        return None;
    }
    let (kind, _) = type_of(schema);
    (kind == "object" || schema.contains_key("allOf") || schema.contains_key("oneOf"))
        .then_some(schema)
}

fn single_ref_wrapper(schema: &Object) -> Option<&Object> {
    let members = schema.get("allOf")?.as_array()?;
    if members.len() != 1 || schema.contains_key("properties") {
        return None;
    }
    let only = members[0].as_object()?;
    only.contains_key("$ref").then_some(only)
}

fn without_null(variants: &[Value]) -> (Vec<Object>, bool) {
    let mut non_null = Vec::new();
    let mut has_null = false;
    for variant in variants.iter().filter_map(Value::as_object) {
        if variant.get("type").and_then(Value::as_str) == Some(NULL_TYPE) {
            has_null = true;
        } else {
            non_null.push(variant.clone());
        }
    }
    (non_null, has_null)
}

fn type_of(schema: &Object) -> (String, bool) {
    match schema.get("type") {
        Some(Value::String(kind)) => (kind.clone(), false),
        Some(Value::Array(kinds)) => {
            let nullable = kinds.iter().any(|k| k.as_str() == Some(NULL_TYPE));
            let kind = kinds
                .iter()
                .filter_map(Value::as_str)
                .find(|k| *k != NULL_TYPE)
                .unwrap_or("");
            (kind.to_string(), nullable)
        }
        _ => {
            let implied = if schema.contains_key("properties")
                || schema.contains_key("additionalProperties")
            {
                "object"
            } else if schema.contains_key("items") {
                "array"
            } else {
                ""
            };
            (implied.to_string(), false)
        }
    }
}

fn ref_name(reference: &str) -> String {
    model_name(reference.rsplit('/').next().unwrap_or(reference))
}

fn model_name(name: &str) -> String {
    if name == "Error" {
        "ModelError".to_string()
    } else {
        name.to_string()
    }
}

fn text(object: &Object, key: &str) -> String {
    object
        .get(key)
        .and_then(Value::as_str)
        .unwrap_or("")
        .to_string()
}

fn chunks(name: &str) -> impl Iterator<Item = &str> {
    name.split(|c: char| !c.is_ascii_alphanumeric())
        .filter(|chunk| !chunk.is_empty())
}

fn capitalised(chunk: &str, lower_rest: bool) -> String {
    let mut chars = chunk.chars();
    let first = chars
        .next()
        .map(|c| c.to_ascii_uppercase())
        .unwrap_or_default();
    let rest = if lower_rest {
        chars.as_str().to_ascii_lowercase()
    } else {
        chars.as_str().to_string()
    };
    format!("{first}{rest}")
}

fn pascal(name: &str) -> String {
    chunks(name)
        .map(|chunk| capitalised(chunk, false))
        .collect()
}

fn camel(name: &str) -> String {
    let mut parts = name.split('_').filter(|chunk| !chunk.is_empty());
    let first = parts.next().unwrap_or("").to_string();
    let rest: String = parts.map(pascal).collect();
    format!("{first}{rest}")
}

fn enum_key(value: &Value) -> String {
    match value {
        Value::String(s) if s.is_empty() => "Empty".to_string(),
        Value::String(s) => chunks(s).map(|chunk| capitalised(chunk, true)).collect(),
        other => capitalised(&other.to_string(), true),
    }
}

fn enum_literal(value: &Value) -> String {
    match value {
        Value::String(s) => format!("'{s}'"),
        other => other.to_string(),
    }
}

fn doc_lines(description: &str) -> String {
    description
        .split('\n')
        .map(|line| format!(" * {line}\n"))
        .collect()
}

impl Model {
    fn render(&self, name: &str) -> String {
        match self {
            Model::Interface {
                description,
                properties,
                enums,
                imports,
                has_enums,
            } => {
                let mut out = render_imports(imports);
                out.push_str(&format!(
                    "/**\n{} * @export\n * @interface {name}\n */\nexport interface {name} {{\n",
                    doc_lines(description)
                ));
                for property in properties {
                    let optional = if property.optional { "?" } else { "" };
                    out.push_str(&format!(
                        "    /**\n{}     */\n    {}{optional}: {};\n",
                        doc_lines(&property.description).replace(" * ", "     * "),
                        property.name,
                        property.ts_type
                    ));
                }
                out.push_str("}\n\n");
                if *has_enums {
                    for e in enums {
                        out.push('\n');
                        out.push_str(&render_enum("/**\n * @export\n */\n", &e.name, &e.values));
                    }
                    out.push_str("\n\n");
                }
                out
            }
            Model::Alias {
                description,
                ts_type,
                imports,
            } => format!(
                "{}/**\n * @type {name}\n{} * @export\n */\nexport type {name} = {ts_type};\n\n",
                render_imports(imports),
                doc_lines(description)
            ),
            Model::Enum {
                description,
                values,
            } => {
                format!(
                    "\n{}\n\n",
                    render_enum(
                        &format!("/**\n{} * @export\n */\n", doc_lines(description)),
                        name,
                        values
                    )
                )
            }
        }
    }
}

fn render_imports(imports: &[String]) -> String {
    if imports.is_empty() {
        return String::new();
    }
    let lines: String = imports
        .iter()
        .map(|name| format!("import type {{ {name} }} from './{name}';\n"))
        .collect();
    format!("{lines}\n")
}

fn render_enum(doc: &str, name: &str, values: &[Value]) -> String {
    let members: String = values
        .iter()
        .map(|value| format!("    {}: {},\n", enum_key(value), enum_literal(value)))
        .collect();
    format!(
        "{doc}export const {name} = {{\n{members}}} as const;\nexport type {name} = typeof {name}[keyof typeof {name}];\n"
    )
}
