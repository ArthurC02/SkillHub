func TestAFileWithoutAGeneratedHeaderAtTheSamePathIsRefused(t *testing.T) {
	t.Parallel()
	root := t.TempDir()
	writeTree(t, root, map[string]string{"apps/db/db.go": "package x\n\n// one\n// two\n// three\n// four\nfunc f() {}\n"})
	problems := commentBudgetProblems(root)
	if len(problems) != 1 || !strings.HasPrefix(problems[0], "comment-budget: apps/db/db.go has 1 comments to remove") {
		t.Fatalf("a hand-written file was exempt: %v", problems)
	}
}

func TestEachWorkLogShapeInACommentIsFlagged(t *testing.T) {
	t.Parallel()
	const kind = "work log in a comment (requirement or ruling id, date, §)"
	rows := []struct{ name, line string }{
		{"a date", "// shipped on 2026-10-16\n"},
		{"a section sign", "// per §3 of the plan\n"},
		{"a ruling id", "// see 甲-12\n"},
		{"a requirement id", "// required by NFR-002\n"},
		{"a recommendation id", "// decided in R-74\n"},
	}
	for _, row := range rows {
		t.Run(row.name, func(t *testing.T) {
			t.Parallel()
			got := commentViolations(row.line, slashComments)
			if len(got) != 1 || got[0] != (commentViolation{1, kind}) {
				t.Fatalf("%q: %v", row.line, got)
			}
		})
	}
}

func TestAnAlgorithmNameWithANumberIsNotAWorkLog(t *testing.T) {
	t.Parallel()
	rows := []struct{ name, line string }{
		{"AES", "// encrypts with AES-256\n"},
		{"RFC", "// follows RFC-822\n"},
		{"HS", "// signs with HS-256\n"},
	}
	for _, row := range rows {
		t.Run(row.name, func(t *testing.T) {
			t.Parallel()
			if got := commentViolations(row.line, slashComments); len(got) != 0 {
				t.Fatalf("%q: %v", row.line, got)
			}
		})
	}
}

