// writeGoFile writes a Go source file under root at the given repo-relative
// path, creating parent directories as needed.
func writeGoFile(t *testing.T, root, relative, body string) {
	t.Helper()
	path := filepath.Join(root, filepath.FromSlash(relative))
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}
}

// writeFakeGenPackage seeds a minimal db/gen so tests do not depend on the
// real, 193-method generated package. Three methods is enough to exercise
// secondDataLayerMinHits.
func writeFakeGenPackage(t *testing.T, root string) {
	t.Helper()
	writeGoFile(t, root, genDirRelative+"/fake.sql.go", `// Code generated by sqlc. DO NOT EDIT.
package gen

import "context"

type Queries struct{}

func (q *Queries) CreateUser(ctx context.Context, arg CreateUserParams) (User, error) {
	return User{}, nil
}
func (q *Queries) GetUser(ctx context.Context, id int64) (User, error) {
	return User{}, nil
}
func (q *Queries) DeleteUser(ctx context.Context, id int64) error {
	return nil
}

type CreateUserParams struct{ Email string }
type User struct{ ID int64 }
`)
}

func TestSecondDataLayerProblemsFlagsThreeMatchingMethods(t *testing.T) {
	root := t.TempDir()
	writeFakeGenPackage(t, root)
	// A replica pulls its types from gen, exactly as a real stand-in would
	// have to for callers built against gen's Params/Row types to compile
	// against it. This is the shape the check exists to catch.
	writeGoFile(t, root, "apps/platform/internal/fake/mem.go", `package fake

import (
	"context"

	"example.com/skillhub/apps/platform/internal/foundation/persistence/db/gen"
)

type memQueries struct{}

func (m *memQueries) CreateUser(ctx context.Context, arg gen.CreateUserParams) (gen.User, error) {
	return gen.User{}, nil
}
func (m *memQueries) GetUser(ctx context.Context, id int64) (gen.User, error) {
	return gen.User{}, nil
}
func (m *memQueries) DeleteUser(ctx context.Context, id int64) error {
	return nil
}
`)

	problems := secondDataLayerProblems(root)
	if len(problems) != 1 {
		t.Fatalf("got %d problems, want 1: %#v", len(problems), problems)
	}
	for _, want := range []string{"memQueries", "CreateUser", "GetUser", "DeleteUser", "PORT-008"} {
		if !strings.Contains(problems[0], want) {
			t.Errorf("problem missing %q: %s", want, problems[0])
		}
	}
}

