func TestSecondDataLayerProblemsRequiresSignatureNotJustName(t *testing.T) {
	root := t.TempDir()
	writeFakeGenPackage(t, root)
	// Same three method names as db/gen, but a caller-facing service shape
	// (an identity.Workspace parameter, no gen.*Params) rather than a
	// replica. This is the apps/platform/internal/trial/design.Service shape
	// from the design doc; a name-only match would misfire on it.
	writeGoFile(t, root, "apps/platform/internal/fake/service.go", `package fake

import "context"

type workspace struct{}

type Service struct{}

func (s *Service) CreateUser(ctx context.Context, ws workspace, email string) (int64, error) {
	return 0, nil
}
func (s *Service) GetUser(ctx context.Context, ws workspace, id int64) (int64, error) {
	return 0, nil
}
func (s *Service) DeleteUser(ctx context.Context, ws workspace, id int64) error {
	return nil
}
`)

	if problems := secondDataLayerProblems(root); len(problems) != 0 {
		t.Fatalf("matching names with a different signature must not be flagged: %#v", problems)
	}
}

// TestSecondDataLayerProblemsReadsCodeNotComments guards against the exact bug
// require_db_guard.go's own history warns about: a first version of that
// check searched raw file text for a marker, and its own explanatory comment
// contained that marker, so deleting the real code left the check satisfied
// by nothing but prose. This fixture puts the three method names and their
// gen-qualified signatures in a comment only — no FuncDecl exists — so an
// AST-based check must see zero methods and a text-based one would not.
func TestSecondDataLayerProblemsReadsCodeNotComments(t *testing.T) {
	root := t.TempDir()
	writeFakeGenPackage(t, root)
	writeGoFile(t, root, "apps/platform/internal/fake/mem.go", `package fake

// type memQueries struct{}
//
// func (m *memQueries) CreateUser(ctx context.Context, arg gen.CreateUserParams) (gen.User, error) {
// 	return gen.User{}, nil
// }
// func (m *memQueries) GetUser(ctx context.Context, id int64) (gen.User, error) {
// 	return gen.User{}, nil
// }
// func (m *memQueries) DeleteUser(ctx context.Context, id int64) error {
// 	return nil
// }
`)

	if problems := secondDataLayerProblems(root); len(problems) != 0 {
		t.Fatalf("methods that exist only in a comment must not be flagged: %#v", problems)
	}
}

func TestSecondDataLayerProblemsIgnoresGenItself(t *testing.T) {
	root := t.TempDir()
	writeFakeGenPackage(t, root)
	// db/gen must never be flagged against itself.
	if problems := secondDataLayerProblems(root); len(problems) != 0 {
		t.Fatalf("db/gen was flagged as a second copy of itself: %#v", problems)
	}
}

// TestTheRealRepositoryHasNoSecondDataLayer keeps the check pointed at the
// tree it exists for. As of writing, db/sqlc.yaml does not emit a Querier
// interface, so there is exactly one data layer (*gen.Queries, 193 methods)
// and this must stay green.
func TestTheRealRepositoryHasNoSecondDataLayer(t *testing.T) {
	root, err := findRepoRoot()
	if err != nil {
		t.Skipf("not inside the repository: %v", err)
	}
	sigs, err := genMethodSignatures(root)
	if err != nil {
		t.Fatal(err)
	}
	if len(sigs) < 100 {
		t.Fatalf("found only %d db/gen methods; the scan is probably looking in the wrong place", len(sigs))
	}
	if got, want := sigs["CreateUser"], "func(Context, CreateUserParams) (User, error)"; got != want {
		t.Errorf("CreateUser normalized signature = %q, want %q", got, want)
	}
	if problems := secondDataLayerProblems(root); len(problems) != 0 {
		t.Errorf("02:PORT-008 violation(s) found in the real tree: %#v", problems)
	}
}
